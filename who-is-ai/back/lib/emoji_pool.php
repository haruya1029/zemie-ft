/* ========================================
   2. 登録済み絵文字をすべて取得
======================================== */

function getAllEmojis(): array
{
    $all = [];

    foreach (getEmojiCategories() as $category) {
        $all = array_merge($all, $category);
    }

    return array_values(array_unique($all));
}

/* ========================================
   3. 通常のカテゴリー別ランダム12個
======================================== */

function generateEmojiPool(): array
{
    $selected = [];

    // 4カテゴリーから3個ずつ
    foreach (getEmojiCategories() as $emojis) {

        shuffle($emojis);

        $picked = array_slice($emojis, 0, 3);

        $selected = array_merge(
            $selected,
            $picked
        );
    }

    shuffle($selected);

    return $selected;
}

