/* ========================================
   5. Geminiが使えない場合の候補生成
======================================== */

function generateFallbackEmojiPool(
    string $question,
    string $answer
): array
{
    $allEmojis = getAllEmojis();
    $keywordMap = getEmojiKeywordMap();

    // 関連候補を格納
    $relatedCandidates = [];

    // 回答文に含まれるキーワードを探す
    foreach ($keywordMap as $keyword => $emojis) {

        if (
            mb_stripos(
                $answer,
                $keyword,
                0,
                'UTF-8'
            ) !== false
        ) {
            $relatedCandidates = array_merge(
                $relatedCandidates,
                $emojis
            );
        }
    }

    // お題が動物関係なら動物絵文字を優先
    if (
        mb_strpos($question, '動物') !== false ||
        mb_strpos($question, '生き物') !== false
    ) {
        $relatedCandidates = array_merge(
            $relatedCandidates,
            [
                '🦁', '🐯', '🐱', '🐶',
                '🐺', '🦊', '🐻', '🐼',
                '🐰', '🦍', '🐬', '🐾'
            ]
        );
    }

    // お題が旅行関係なら旅行絵文字を優先
    if (
        mb_strpos($question, '行きたい') !== false ||
        mb_strpos($question, '旅行') !== false
    ) {
        $relatedCandidates = array_merge(
            $relatedCandidates,
            [
                '✈️', '🌍', '📷', '🎒',
                '🏝️', '🏨', '🧳', '🧭'
            ]
        );
    }

    // お題がお金関係なら関連候補を追加
    if (
        mb_strpos($question, '万円') !== false ||
        mb_strpos($question, 'お金') !== false
    ) {
        $relatedCandidates = array_merge(
            $relatedCandidates,
            [
                '💰', '🛍️', '🎁', '✈️',
                '🚗', '🏠', '💻', '💭'
            ]
        );
    }

    // 重複と未登録絵文字を除外
    $relatedCandidates = array_values(
        array_intersect(
            array_unique($relatedCandidates),
            $allEmojis
        )
    );

    shuffle($relatedCandidates);

    // 関連絵文字を最大6個
    $related = array_slice(
        $relatedCandidates,
        0,
        6
    );

    // 6個未満なら登録済み候補で補充
    $remaining = array_values(
        array_diff($allEmojis, $related)
    );

    shuffle($remaining);

    while (count($related) < 6) {
        $related[] = array_shift($remaining);
    }

    // 追加のランダム6個
    $remaining = array_values(
        array_diff($allEmojis, $related)
    );

    shuffle($remaining);

    $random = array_slice(
        $remaining,
        0,
        6
    );

    $pool = array_merge(
        $related,
        $random
    );

    shuffle($pool);

    return $pool;
}
